#!/usr/bin/env python3
"""Generate tr7_c/src/tr7_c_stubs.c: every tr7.h symbol the Ada subset does not.

The full symbol set comes from include/tr7.h (a copy of upstream TR7's
header, 0BSD); the implemented subset comes from the External_Name aspects
in tr7_c.ads / tr7_c.adb.  The difference is emitted as C stubs returning
zero, so a C program links against this library exactly as against
upstream's.

  gen_abi.py                    regenerate the checked-in stub file
  gen_abi.py --check            fail if the checked-in file is not current
  gen_abi.py --check-lib LIB    fail if nm shows LIB missing a header symbol
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "tr7_c" / "include" / "tr7.h"
STUBS = ROOT / "tr7_c" / "src" / "tr7_c_stubs.c"
SOURCES = ROOT / "tr7_c" / "src"

#  Words that may end a type but never name a parameter: if the last
#  identifier of a parameter is one of these, the header declared the
#  parameter without a name and there is nothing to silence.
TYPE_WORDS = {
    "int", "char", "long", "short", "unsigned", "signed", "float", "double",
    "void", "const", "volatile", "struct", "union", "enum", "size_t",
    "tr7_t", "tr7_int_t", "tr7_uint_t", "tr7_char_t", "tr7_engine_t",
    "tr7_pair_t", "tr7_cell_t", "tr7_double_t", "tr7_config_t", "tr7_play_t",
    "tr7_malloc_t", "tr7_free_t", "tr7_cptr_cb_t", "tr7_strid_t",
    "tr7_compare_t", "tr7_getlib_error_t", "FILE",
}


def strip_noise(text):
    """Drop comments and preprocessor lines: only real declarations remain."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    text = re.sub(r"^[ \t]*#[^\n]*", " ", text, flags=re.M)
    return text


def split_params(params):
    """Split a parameter list on top-level commas only."""
    params = params.strip()
    if params in ("", "void"):
        return []
    out, depth, cur = [], 0, []
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    out.append("".join(cur).strip())
    return out


def param_name(param):
    """The parameter's name, or None when the header left it unnamed."""
    m = re.search(r"\(\s*\*\s*([A-Za-z_]\w*)\s*\)", param)
    if m:
        return m.group(1)
    without_arrays = re.sub(r"\[[^\]]*\]", "", param)
    ids = re.findall(r"[A-Za-z_]\w*", without_arrays)
    if not ids or ids[-1] in TYPE_WORDS:
        return None
    return ids[-1]


def declarations(text):
    """Yield (return_type, name, [params]) for each TR7_EXPORT declaration."""
    seen = set()
    pos = 0
    export = re.compile(r"\bTR7_EXPORT\b")
    while True:
        m = export.search(text, pos)
        if m is None:
            return
        depth, i = 0, m.end()
        while i < len(text):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
            elif text[i] == ";" and depth == 0:
                break
            i += 1
        decl = text[m.start():i + 1]
        pos = i + 1
        d = re.match(r"TR7_EXPORT\s+(.*?)\b([A-Za-z_]\w*)\s*\((.*)\)\s*;",
                     decl, re.S)
        if d is None:
            raise SystemExit(f"gen_abi.py: cannot parse: {decl!r}")
        name = d.group(2)
        if name in seen:
            continue
        seen.add(name)
        yield d.group(1).strip(), name, split_params(d.group(3))


def header_declarations():
    return list(declarations(strip_noise(HEADER.read_text())))


def subset():
    """The symbols tr7_c implements, from its Export aspects.

    External_Name also appears on Import aspects (libc's malloc and free,
    which this library calls); only Export turns an Ada name into a
    library symbol, so only those count as implemented."""
    names = set()
    for src in sorted(SOURCES.glob("tr7_c.ad*")):
        text = src.read_text()
        for clause in re.findall(r"with\s+([^;]*);", text, re.S):
            if "Export" not in clause or "External_Name" not in clause:
                continue
            m = re.search(r'External_Name\s*=>\s*"([^"]+)"', clause)
            if m:
                names.add(m.group(1))
    return names


def generate():
    decls = header_declarations()
    impl = subset()
    missing = impl - {name for _, name, _ in decls}
    if missing:
        raise SystemExit(
            "gen_abi.py: exported by Ada but absent from the header: "
            + ", ".join(sorted(missing)))
    stubs = [d for d in decls if d[1] not in impl]
    lines = [
        "/* Generated by scripts/gen_abi.py from tr7_c/include/tr7.h"
        " -- do not edit. */",
        "/*",
        f" * {len(stubs)} of {len(decls)} header symbols are implemented in Ada"
        " (tr7_c/src/tr7_c.ad[s]b);",
        " * the rest are zero-returning stubs so that a C program links"
        " against this library",
        " * exactly as against upstream's.",
        " */",
        '#include "tr7.h"',
        "",
    ]
    for ret, name, params in stubs:
        lines.append(f"TR7_EXPORT {ret} {name}({', '.join(params)})")
        lines.append("{")
        for p in params:
            pname = param_name(p)
            if pname:
                lines.append(f"   (void){pname};")
        if ret != "void":
            #  A compound literal zeroes anything: scalars, pointers and the
            #  struct returns (tr7_foreign_t) alike, where `return 0;`
            #  would not type-check.
            lines.append(f"   return ({ret}){{0}};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def check_lib(lib):
    nm = subprocess.run(["nm", "--defined-only", lib],
                        capture_output=True, text=True, check=True).stdout
    defined = set()
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) >= 3 and re.fullmatch(r"[0-9a-fA-F]+", parts[0]):
            defined.add(parts[2])
    header = {name for _, name, _ in header_declarations()}
    absent = sorted(header - defined)
    if absent:
        print(f"gen_abi.py: {lib} does not define {len(absent)} of the "
              f"{len(header)} tr7.h symbols:", file=sys.stderr)
        for name in absent[:20]:
            print(f"  {name}", file=sys.stderr)
        return 1
    print(f"gen_abi.py: all {len(header)} tr7.h symbols defined in {lib}")
    return 0


def main(argv):
    if "--check" in argv:
        want = generate()
        have = STUBS.read_text() if STUBS.exists() else ""
        if want != have:
            print("gen_abi.py: tr7_c/src/tr7_c_stubs.c is stale; "
                  "rerun scripts/gen_abi.py", file=sys.stderr)
            return 1
        print("gen_abi.py: stubs are current")
        return 0
    if "--check-lib" in argv:
        return check_lib(argv[argv.index("--check-lib") + 1])
    STUBS.write_text(generate())
    print(f"gen_abi.py: wrote {STUBS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
